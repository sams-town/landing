<?php
/**
 * BeethovenPets aaPanel Installer
 * -----------------------------------------------------------
 * Same as cPanel installer, but adds:
 *   1. opcache_reset() + apcu_clear_cache() + realpath_cache_clear for
 *      aaPanel PHP-FPM pools.
 *   2. Detects common aaPanel document root and reports to user.
 *   3. Optional: tries to write a PHP-FPM pool restart marker file
 *      (informational only — aaPanel has no PHP API for that).
 *
 * Upload to /www/wwwroot/yoursite.com/deploy/aapanel-install.php then visit.
 */

$step = isset($_GET['step']) ? (int)$_GET['step'] : 1;
$errors = []; $warnings = []; $success = [];

$aaPanelHints = [
    'Server User (common)' => file_exists('/www/server/php') ? '✅ Detected aaPanel PHP stack at /www/server/php' : '⚠️ /www/server/php not found',
    'Site root path'       => @realpath(__DIR__ . '/..'),
    'Open Basedir'         => ini_get('open_basedir') ?: '(not active — good)',
    'disable_functions'    => (strlen(ini_get('disable_functions')) > 300) ? '⚠️ Many functions disabled — exec/passthru likely blocked (fine, installer works without)' : 'OK',
];

$checks = [
    'PHP >= 7.4' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO MySQL'  => extension_loaded('pdo_mysql'),
    'mbstring'   => extension_loaded('mbstring'),
    'JSON'       => extension_loaded('json'),
    'Session'    => extension_loaded('session'),
    'Writable: includes/' => is_writable(__DIR__ . '/../includes'),
    'Writable: uploads/'  => is_writable(__DIR__ . '/../uploads'),
    'Writable: logs/'     => is_writable(__DIR__ . '/../logs'),
    'password_hash (bcrypt)' => function_exists('password_hash'),
    'File uploads'        => (bool)ini_get('file_uploads'),
];

if (!empty($_POST) && $step === 2) {
    $host = trim($_POST['db_host'] ?? '127.0.0.1');
    $port = trim($_POST['db_port'] ?? '3306');
    $name = trim($_POST['db_name'] ?? '');
    $user = trim($_POST['db_user'] ?? '');
    $pass = $_POST['db_pass'] ?? '';
    $siteName = trim($_POST['site_name'] ?? 'BeethovenPets');
    $adminEmail = trim($_POST['admin_email'] ?? '');
    $adminPass  = $_POST['admin_password'] ?? '';

    try {
        $pdo = new PDO("mysql:host=$host;port=$port;charset=utf8mb4", $user, $pass, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        ]);
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `$name` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        $pdo->exec("USE `$name`");
        $success[] = "Connected to MySQL successfully. Database `$name` ready.";

        $sqlPath = realpath(__DIR__ . '/../database/beethovenpets_schema.sql');
        if ($sqlPath && is_file($sqlPath)) {
            $sql = file_get_contents($sqlPath);
            $stmts = array_values(array_filter(array_map('trim', explode(';', $sql))));
            foreach ($stmts as $stmt) {
                if (empty($stmt) || str_starts_with($stmt, '--')) continue;
                try { $pdo->exec($stmt); }
                catch (Throwable $e) { $warnings[] = "SQL skip: " . substr($e->getMessage(),0,120); }
            }
            $success[] = count($stmts) . " SQL statements imported from schema file.";
        } else {
            $warnings[] = "beethovenpets_schema.sql not found in /database/ — import manually via phpMyAdmin.";
        }

        if ($adminEmail && strlen($adminPass) >= 4) {
            $hash = password_hash($adminPass, PASSWORD_BCRYPT);
            try {
                $pdo->exec("INSERT INTO admins (full_name, email, password_hash, role) VALUES
                  ('Super Admin', " . $pdo->quote($adminEmail) . ", " . $pdo->quote($hash) . ", 'super_admin')
                  ON DUPLICATE KEY UPDATE
                  password_hash=" . $pdo->quote($hash) . ",
                  full_name='Super Admin',
                  role='super_admin',
                  updated_at=NOW()");
                $success[] = "Super-admin credentials updated: $adminEmail";
            } catch (Throwable $e) { $errors[] = "Admin update failed: " . $e->getMessage(); }
        }

        try {
            $pdo->exec("INSERT INTO site_settings (setting_key, setting_value, setting_group) VALUES
              ('site_name', " . $pdo->quote($siteName) . ", 'contact')
              ON DUPLICATE KEY UPDATE setting_value=" . $pdo->quote($siteName));
        } catch (Throwable $e) { $warnings[] = "Couldn't save site_name setting."; }

        $configPath = realpath(__DIR__ . '/../includes') . '/config.php';
        $configContent = '<?php
/**
 * BeethovenPets Site Config — generated by deploy/aapanel-install.php on ' . date('r') . '
 */
define("DB_HOST", "' . addslashes($host) . '");
define("DB_PORT", "' . addslashes($port) . '");
define("DB_NAME", "' . addslashes($name) . '");
define("DB_USER", "' . addslashes($user) . '");
define("DB_PASS", "' . addslashes($pass) . '");
define("DB_CHARSET", "utf8mb4");

define("SITE_NAME", "' . addslashes($siteName) . '");
define("SITE_URL",  "https://" . ($_SERVER["HTTP_HOST"] ?? "localhost") . "/");
define("ADMIN_PATH", "/admin");

define("UPLOAD_DIR",  __DIR__ . "/../uploads");
define("LOG_DIR",     __DIR__ . "/../logs");

if (session_status() === PHP_SESSION_NONE) {
    @session_name("BEETHOVENPETS_SESS");
    @session_start();
}

error_reporting(0);
ini_set("display_errors", 0);
ini_set("log_errors", 1);
ini_set("error_log", LOG_DIR . "/php-errors.log");

date_default_timezone_set("Asia/Jakarta");
';
        if (@file_put_contents($configPath, $configContent)) {
            $success[] = "config.php written with database credentials.";
        } else {
            $errors[] = "Could not write config.php — permissions issue. CHMOD includes/ to 755 via aaPanel File Manager.";
        }

        // aaPanel-specific caches
        if (function_exists('opcache_reset'))    { @opcache_reset();    $success[] = "OPcache flushed for PHP-FPM pool."; }
        if (function_exists('apcu_clear_cache')) { @apcu_clear_cache(true); $success[] = "APCu user cache cleared."; }
        @clearstatcache(true);
        if (function_exists('realpath_cache_clear')) { @realpath_cache_clear(); }
        if (function_exists('opcache_invalidate')) { @opcache_invalidate($configPath, true); }
        $success[] = "PHP-FPM stat cache cleared (aaPanel users: if you see stale config, restart PHP-FPM in aaPanel → Software Store → PHP X → Service → Reload).";

        // Write pool reload hint
        $poolPath = '/www/server/php/' . (PHP_MAJOR_VERSION . PHP_MINOR_VERSION) . '/var/run/php-fpm.pid';
        if (@file_put_contents(__DIR__ . '/../logs/.pool-reload-needed', "Please reload PHP-FPM pool in aaPanel dashboard if you see stale pages.\nGenerated: " . date('r'))) {
            $warnings[] = "Hint file written to logs/.pool-reload-needed";
        }

        $step = 3;
    } catch (Throwable $e) {
        $errors[] = "❌ DB failed: " . $e->getMessage();
    }
}


/**
 * BeethovenPets cPanel Installer / Reinstaller
 * -----------------------------------------------------------
 * USAGE:
 *   1. Zip+upload all project files to /public_html/
 *   2. Upload THIS file to /public_html/deploy/cpanel-install.php
 *   3. Open browser → https://yoursite.com/deploy/cpanel-install.php
 *   4. Follow wizard, enter DB creds + admin email/password.
 *   5. Script writes includes/config.php and imports SQL from
 *      ../database/beethovenpets_schema.sql if found (or from inline).
 *   6. ✅ Delete this file AND the /deploy folder after install!
 *
 * NO SSH REQUIRED. Uses only filesystem + PHP PDO.
 */

$step = isset($_GET['step']) ? (int)$_GET['step'] : 1;
$errors = [];
$warnings = [];
$success = [];

// ---- ENVIRONMENT CHECK ----
$checks = [
    'PHP >= 7.4' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO MySQL'  => extension_loaded('pdo_mysql'),
    'mbstring'   => extension_loaded('mbstring'),
    'JSON'       => extension_loaded('json'),
    'Session'    => extension_loaded('session'),
    'Writable: includes/' => is_writable(__DIR__ . '/../includes'),
    'Writable: uploads/'  => is_writable(__DIR__ . '/../uploads'),
    'Writable: logs/'     => is_writable(__DIR__ . '/../logs'),
    'password_hash (bcrypt)' => function_exists('password_hash'),
];

if (!empty($_POST) && $step === 2) {
    // DB test
    $host = trim($_POST['db_host'] ?? 'localhost');
    $port = trim($_POST['db_port'] ?? '3306');
    $name = trim($_POST['db_name'] ?? '');
    $user = trim($_POST['db_user'] ?? '');
    $pass = $_POST['db_pass'] ?? '';
    $siteName = trim($_POST['site_name'] ?? 'BeethovenPets');
    $adminEmail = trim($_POST['admin_email'] ?? '');
    $adminPass  = $_POST['admin_password'] ?? '';

    try {
        $pdo = new PDO("mysql:host=$host;port=$port;charset=utf8mb4", $user, $pass, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        ]);
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `$name` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        $pdo->exec("USE `$name`");
        $success[] = "Connected to MySQL successfully. Database `$name` ready.";

        // Import SQL
        $sqlPath = realpath(__DIR__ . '/../database/beethovenpets_schema.sql');
        if ($sqlPath && is_file($sqlPath)) {
            $sql = file_get_contents($sqlPath);
            $statements = array_values(array_filter(array_map('trim', explode(';', $sql))));
            foreach ($statements as $stmt) {
                if (empty($stmt) || str_starts_with($stmt, '--')) continue;
                try { $pdo->exec($stmt); }
                catch (Throwable $e) { $warnings[] = "SQL skip: " . substr($e->getMessage(),0,120); }
            }
            $success[] = count($statements) . " SQL statements imported from schema file.";
        } else {
            $warnings[] = "beethovenpets_schema.sql not found — import manually via phpMyAdmin later.";
        }

        // Update / create admin user
        if ($adminEmail && strlen($adminPass) >= 4) {
            $hash = password_hash($adminPass, PASSWORD_BCRYPT);
            try {
                $pdo->exec("INSERT INTO admins (full_name, email, password_hash, role) VALUES
                  ('Super Admin', " . $pdo->quote($adminEmail) . ", " . $pdo->quote($hash) . ", 'super_admin')
                  ON DUPLICATE KEY UPDATE
                  password_hash=" . $pdo->quote($hash) . ",
                  full_name='Super Admin',
                  role='super_admin',
                  updated_at=NOW()");
                $success[] = "Super-admin credentials updated: $adminEmail";
            } catch (Throwable $e) {
                $errors[] = "Admin update failed: " . $e->getMessage();
            }
        }

        // Update site_name setting
        try {
            $pdo->exec("INSERT INTO site_settings (setting_key, setting_value, setting_group) VALUES
              ('site_name', " . $pdo->quote($siteName) . ", 'contact')
              ON DUPLICATE KEY UPDATE setting_value=" . $pdo->quote($siteName));
        } catch (Throwable $e) { $warnings[] = "Couldn't save site_name setting."; }

        // Write config.php
        $configPath = realpath(__DIR__ . '/../includes') . '/config.php';
        $configContent = '<?php
/**
 * BeethovenPets Site Config — generated by deploy/cpanel-install.php on ' . date('r') . '
 */
define("DB_HOST", "' . addslashes($host) . '");
define("DB_PORT", "' . addslashes($port) . '");
define("DB_NAME", "' . addslashes($name) . '");
define("DB_USER", "' . addslashes($user) . '");
define("DB_PASS", "' . addslashes($pass) . '");
define("DB_CHARSET", "utf8mb4");

define("SITE_NAME", "' . addslashes($siteName) . '");
define("SITE_URL",  "https://" . ($_SERVER["HTTP_HOST"] ?? "localhost") . "/");
define("ADMIN_PATH", "/admin");

define("UPLOAD_DIR",  __DIR__ . "/../uploads");
define("LOG_DIR",     __DIR__ . "/../logs");

if (session_status() === PHP_SESSION_NONE) {
    @session_name("BEETHOVENPETS_SESS");
    @session_start();
}

error_reporting(0);
ini_set("display_errors", 0);
ini_set("log_errors", 1);
ini_set("error_log", LOG_DIR . "/php-errors.log");

date_default_timezone_set("Asia/Jakarta");
';
        if (@file_put_contents($configPath, $configContent)) {
            $success[] = "config.php written successfully with your database credentials.";
        } else {
            $errors[] = "Could not write config.php — permissions issue. Create manually with credentials above.";
        }

        // Clear cPanel PHP opcache if enabled
        if (function_exists('opcache_reset')) { @opcache_reset(); $success[] = "PHP OPcache cleared."; }
        clearstatcache();

        $step = 3;
    } catch (Throwable $e) {
        $errors[] = "❌ Database connection failed: " . $e->getMessage();
    }
}

